module undefined_method

SECTION DRV_CODE

; -----------------------------------------------------------------------------
; _undefined_method - Обработчик вызова неопределенного метода
; -----------------------------------------------------------------------------
; Вход: Исполняемый код вызвал метод, который не был инициализирован
; Выход: Система останавливается с сообщением об ошибке
; -----------------------------------------------------------------------------

PUBLIC _undefined_method

_undefined_method:
    di                    ; Запрещаем прерывания
