#ifndef BIOS_ERRORS_H
#define BIOS_ERRORS_H

/*
 * СТАНДАРТНЫЕ КОДЫ ОШИБОК BIOS ALESTE
 * 
 * Соглашение:
 * - Успех: A=0, Carry=0
 * - Ошибка: A=код, Carry=1
 * - Коды 0x00-0x7F для системы, 0x80-0xFF для приложений
 */

// ==============================================================================
// СИСТЕМНЫЕ ОШИБКИ (0x00-0x3F)
// ==============================================================================

// Успех (обязательно должен быть 0)
#define ERR_SUCCESS           0x00

// Общие ошибки
#define ERR_NOT_SUPPORTED     0x01  // Операция не поддерживается
#define ERR_INVALID_PARAM     0x02  // Неверный параметр
#define ERR_OUT_OF_RANGE      0x03  // Выход за допустимые пределы
#define ERR_TIMEOUT           0x04  // Таймаут операции
#define ERR_BUSY              0x05  // Устройство занято
#define ERR_AGAIN             0x06  // Повторить операцию

// Ошибки памяти
#define ERR_OUT_OF_MEMORY     0x10  // Недостаточно памяти
#define ERR_INVALID_ADDRESS   0x11  // Неверный адрес
#define ERR_MEMORY_PROTECT    0x12  // Нарушение защиты памяти
#define ERR_MMU_FAULT         0x13  // Ошибка MMU

// Ошибки устройств
#define ERR_NO_DEVICE         0x20  // Устройство не найдено
#define ERR_DEVICE_BUSY       0x21  // Устройство занято
#define ERR_DEVICE_FAULT      0x22  // Сбой устройства
#define ERR_DEVICE_OFFLINE    0x23  // Устройство отключено

// Ошибки ввода-вывода
#define ERR_IO_ERROR          0x30  // Ошибка ввода-вывода
#define ERR_IO_TIMEOUT        0x31  // Таймаут ввода-вывода
#define ERR_IO_PROTOCOL       0x32  // Ошибка протокола

// ==============================================================================
// ОШИБКИ ФАЙЛОВОЙ СИСТЕМЫ (0x40-0x5F)
// ==============================================================================

#define ERR_FILE_NOT_FOUND    0x40  // Файл не найден
#define ERR_PATH_NOT_FOUND    0x41  // Путь не найден
#define ERR_ACCESS_DENIED     0x42  // Доступ запрещен
#define ERR_DISK_FULL         0x43  // Диск переполнен
#define ERR_DISK_ERROR        0x44  // Ошибка диска
#define ERR_NOT_A_DIRECTORY   0x45  // Не директория
#define ERR_IS_DIRECTORY      0x46  // Это директория
#define ERR_FILE_EXISTS       0x47  // Файл уже существует

// ==============================================================================
// СЕТЕВЫЕ ОШИБКИ (0x60-0x7F)
// ==============================================================================

#define ERR_NET_DOWN          0x60  // Сеть недоступна
#define ERR_NET_TIMEOUT       0x61  // Таймаут сети
#define ERR_CONNECTION_LOST   0x62  // Соединение потеряно
#define ERR_CONNECTION_REFUSED 0x63 // Соединение отклонено

// ==============================================================================
// ПРИКЛАДНЫЕ ОШИБКИ (0x80-0xFF) - для пользовательских программ
// ==============================================================================

// Первая свободная для приложений
#define ERR_APP_BASE          0x80

// ==============================================================================
// ВСПОМОГАТЕЛЬНЫЕ МАКРОСЫ
// ==============================================================================

// Проверка на успех
#define IS_SUCCESS(carry_flag) (!(carry_flag))

// Проверка на ошибку  
#define IS_ERROR(carry_flag) (carry_flag)

// Получить код ошибки из регистра A
#define ERROR_CODE(a_reg) (a_reg)

#endif // BIOS_ERRORS_H