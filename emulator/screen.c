void render_cpu(Z80EX_CONTEXT *cpu)
{
   
    // 2. Оверлей состояния (Ярко-зеленый текст)
    char buf[64];
    uint32_t text_color = 0xFF00FF00; // Green

    // --------------------------------------------
    // Основные и альтернативные регистры (Shadow Registers)
    sprintf(buf, "PC:%04X  SP:%04X", z80ex_get_reg(cpu, regPC), z80ex_get_reg(cpu, regSP));
    draw_text(5, 5, buf, text_color);

    sprintf(buf, "AF:%04X  AF':%04X", z80ex_get_reg(cpu, regAF), z80ex_get_reg(cpu, regAF_));
    draw_text(5, 15, buf, text_color);

    sprintf(buf, "BC:%04X  BC':%04X", z80ex_get_reg(cpu, regBC), z80ex_get_reg(cpu, regBC_));
    draw_text(5, 25, buf, text_color);

    sprintf(buf, "DE:%04X  DE':%04X", z80ex_get_reg(cpu, regDE), z80ex_get_reg(cpu, regDE_));
    draw_text(5, 35, buf, text_color);

    sprintf(buf, "HL:%04X  HL':%04X", z80ex_get_reg(cpu, regHL), z80ex_get_reg(cpu, regHL_));
    draw_text(5, 45, buf, text_color);

    // Добавим индексные регистры, так как они часто важны в BIOS
    sprintf(buf, "IX:%04X  IY':%04X", z80ex_get_reg(cpu, regIX), z80ex_get_reg(cpu, regIY));
    draw_text(5, 55, buf, text_color);

    // -------------------------------------------- 

    // Понадобится подключить z80ex_dasm.h
    char dasm_buf[128];
    uint16_t pc = z80ex_get_reg(cpu, regPC);

    // Внутри render_cpu или функции оверлея
    int t1, t2;
    z80ex_dasm(
        dasm_buf,         // 1: Буфер для текста
        sizeof(dasm_buf), // 2: Размер буфера
        0,                // 3: Флаги (обычно 0)
        &t1,              // 4: T-states основной инструкции
        &t2,              // 5: T-states дополнительно
        dasm_read_byte,   // 6: Ваша новая функция-обертка
        pc,               // 7: Адрес (Z80EX_WORD)
        memory            // 8: user_data (передаем указатель на массив памяти)
    );
    draw_text(5, 65, "INST:", 0xFFFFFF00); // Желтый
    draw_text(50, 65, dasm_buf, 0xFFFFFF00);
    printf("[screen] %s\n", dasm_buf);
}

void update_screen_16k1b(Z80EX_CONTEXT *cpu, uint8_t* memory, uint32_t start) {
    int w = 80;
    int h = 200;
    for (int y = 0; y < h; y++) {
        for (int x = 0; x < w; x++) {
            int src = start + x + y * w;
            if (src >= 0xFFFFFF) break; // Защита от вылета!

            uint8_t color = memory[src];   

            int dst = (x * 8) + (y * (8 * w));
            screen_buffer[dst+0] =  color & 0x80;
            screen_buffer[dst+1] =  color & 0x40;
            screen_buffer[dst+2] =  color & 0x20;
            screen_buffer[dst+3] =  color & 0x10;
            screen_buffer[dst+4] =  color & 0x08;
            screen_buffer[dst+5] =  color & 0x04;
            screen_buffer[dst+6] =  color & 0x02;
            screen_buffer[dst+7] =  color & 0x01;
        }
    }
}

void update_screen(Z80EX_CONTEXT *cpu, uint8_t* memory, uint32_t start, EScreenMode mode) {
    // Превращаем 8-битные данные из памяти Z80 в 32-битные пиксели для SDL
    switch (mode)
    {
    case EScreenMode_Linear16k1b:
        update_screen_16k1b(cpu,memory,start);
        break;
    
    default:
        break;
    }


    render_cpu(cpu);

    SDL_UpdateTexture(texture, NULL, screen_buffer, SCREEN_WIDTH * sizeof(uint32_t));
    SDL_RenderClear(renderer);
    SDL_RenderCopy(renderer, texture, NULL, NULL);
    // Здесь позже добавим отрисовку текста (регистров)
    SDL_RenderPresent(renderer);
}
